def elige(texto: Texto) -> str:
    if isinstance(texto, str):
        return texto
    return t(*texto)


def tabla(idioma: str) -> str:
    global _idioma
    _idioma = idioma
    _, inicio, fin = README[idioma]
    partes = [inicio, ""]
    for titulo, filas in SECCIONES:
        partes += [
            f"**{elige(titulo)}**",
            "",
            t(
                "| Qué se mide | Umbral | Medido | Comando |",
                "| What is measured | Threshold | Measured | Command |",
            ),
            "|---|---|---|---|",
        ]
        for que, umbral, comando, valor in filas:
            medido = valor() or t(
                "_sin medir: falta el artefacto_", "_not measured: artifact missing_"
            )
            partes.append(f"| {elige(que)} | {elige(umbral)} | {medido} | {comando} |")
        partes.append("")
    partes.append(fin)
    return "\n".join(partes)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="sale 1 si algún README no coincide"
    )
    args = parser.parse_args()

    fallos = 0
    for idioma, (ruta, inicio, fin) in README.items():
        nombre = ruta.relative_to(ROOT)
        texto = ruta.read_text(encoding="utf-8")
        if inicio not in texto or fin not in texto:
            print(
                f"readme_numbers: {nombre} no tiene los marcadores de la tabla", file=sys.stderr
            )
            return 1
        antes, resto = texto.split(inicio, 1)
        _, despues = resto.split(fin, 1)
        nuevo = antes + tabla(idioma) + despues

        if args.check:
            if nuevo != texto:
                print(f"readme_numbers: la tabla de {nombre} NO coincide con los artefactos.")
                fallos += 1
            continue
        ruta.write_text(nuevo, encoding="utf-8")
        print(f"readme_numbers: {nombre} regenerado desde evals/reports/")

    if args.check:
        if fallos:
            print("  Se regenera con `make readme`.")
            return 1
        print("readme_numbers: ok · las dos tablas coinciden con evals/reports/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
